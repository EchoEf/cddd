# 分组：保留每个玩家按出现顺序的前三刀
player_hits = OrderedDict()
for player, boss, dmg in records:
    if player not in player_hits:
        player_hits[player] = []
    if len(player_hits[player]) < 3:
        player_hits[player].append((boss, dmg))


def to_yi(n):
    """原始伤害转亿，四舍五入保留1位小数。"""
    return round(n / 1e8, 1)


def fmt_yi(n):
    """亿单位字符串。"""
    return f"{to_yi(n)}亿"


rows = []
for player, hits in player_hits.items():
    total_raw = sum(d for _, d in hits)
    bosses = [b for b, _ in hits]
    note = "三刀水" if len(hits) == 3 and all(b == "铁匠" for b in bosses) else ""
    # 不足三刀也允许"三刀水"不适用；若三刀以内全铁匠且刀数<3不备注
    rows.append({
        "player": player,
        "hits": hits,
        "total_raw": total_raw,
        "total_yi": to_yi(total_raw),
        "note": note,
        "count": len(hits),
    })

# 按总伤害降序
rows.sort(key=lambda r: r["total_raw"], reverse=True)

# 计算平均总伤害
avg_raw = sum(r["total_raw"] for r in rows) / len(rows)
avg_yi = to_yi(avg_raw)

# 输出表格：带 Unicode 边框，含每刀的 Boss 标注
lines = []
lines.append("⚔️ 工会战伤害统计表 ⚔️")
lines.append("")

# 表头
header = "│ 排名 │ 玩家名        │ 总伤害(亿) │ 第一刀          │ 第二刀          │ 第三刀          │ 备注   │"
sep_top = "┌──────┬───────────────┬────────────┬─────────────────┬─────────────────┬─────────────────┬────────┐"
sep_mid = "├──────┼───────────────┼────────────┼─────────────────┼─────────────────┼─────────────────┼────────┤"
sep_bot = "└──────┴───────────────┴────────────┴─────────────────┴─────────────────┴─────────────────┴────────┘"

lines.append(sep_top)
lines.append(header)
lines.append(sep_mid)

for i, r in enumerate(rows, 1):
    cells = []
    cells.append(f"{i:>4}")
    cells.append(f"{r['player']:<13}")
    cells.append(f"{r['total_yi']:^10.1f}")
    for k in range(3):
        if k < len(r["hits"]):
            boss, dmg = r["hits"][k]
            cells.append(f"{fmt_yi(dmg):<7}({boss:<4})")
        else:
            cells.append("—".center(15))
    cells.append(f"{r['note']:^6}")
    lines.append("│ " + " │ ".join(cells) + " │")

lines.append(sep_bot)
lines.append("")
lines.append(f"📊 玩家总数：{len(rows)} 人")
lines.append(f"💥 平均总伤害：{avg_yi}亿")
lines.append("")

# 不足三刀提示
incomplete = [r for r in rows if r["count"] < 3]
if incomplete:
    lines.append("⚠️ 以下玩家刀数不足三刀，可补充缺失数据：")
    for r in incomplete:
        lines.append(f"   • {r['player']}：当前 {r['count']} 刀")
else:
    lines.append("✅ 所有玩家均已满三刀。")

output = "\n".join(lines)
print(output)

